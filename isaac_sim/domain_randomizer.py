"""
Domain Randomizer — NVIDIA Omniverse Replicator

Applies stochastic perturbations to an existing warehouse USD stage so that
neural networks trained on the synthetic data generalise to real facilities.

All methods accept an optional `seed` argument for reproducible episodes.

Usage:
    from isaac_sim.domain_randomizer import DomainRandomizer
    dr = DomainRandomizer(stage)
    dr.randomize_lighting(seed=42)
    dr.randomize_textures()
    dr.randomize_worker_count(min_workers=2, max_workers=8)
"""

