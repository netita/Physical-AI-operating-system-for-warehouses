# ---------------------------------------------------------------------------
# DomainRandomizer
# ---------------------------------------------------------------------------

class DomainRandomizer:
    """
    Randomises every visual and semantic aspect of the warehouse stage so that
    synthetic training data covers the distribution of real-world appearances.

    Parameters
    ----------
    stage : Usd.Stage
        The live USD stage generated by WarehouseGenerator.
    warehouse_path : str
        Root prim path of the warehouse (default ``/World/Warehouse``).
    """

    WAREHOUSE_PATH = "/World/Warehouse"
    LIGHTING_PATH = "/World/Warehouse/Lighting"
    RACKS_PATH = "/World/Warehouse/Racks"
    ACTORS_PATH = "/World/Actors"

    def __init__(
        self,
        stage: Optional[Usd.Stage] = None,
        warehouse_path: str = WAREHOUSE_PATH,
    ) -> None:
        self._stage = stage or get_current_stage()
        self._warehouse_path = warehouse_path
        self._lighting_path = f"{warehouse_path}/Lighting"
        self._racks_path = f"{warehouse_path}/Racks"
        self._actors_path = "/World/Actors"
        self._ensure_actors_scope()

        # Internal state
        self._worker_prims: List[Usd.Prim] = []
        self._forklift_prims: List[Usd.Prim] = []
        self._inventory_prims: List[Usd.Prim] = []

    # ------------------------------------------------------------------
    # Lighting randomisation
    # ------------------------------------------------------------------

    def randomize_lighting(
        self,
        seed: Optional[int] = None,
        intensity_range: Tuple[float, float] = (1000.0, 8000.0),
        cct_range: Tuple[float, float] = (2700.0, 6500.0),  # Kelvin
        shadow_softness_range: Tuple[float, float] = (0.0, 10.0),
    ) -> None:
        """
        Vary every light in /Lighting — intensity, colour temperature and
        shadow softness — to simulate different times of day and fixture types.
        """
        rng = random.Random(seed)

        lighting_prim = self._stage.GetPrimAtPath(self._lighting_path)
        if not lighting_prim.IsValid():
            return

        for prim in lighting_prim.GetChildren():
            if not any(
                prim.IsA(t)
                for t in (
                    UsdLux.RectLight,
                    UsdLux.SphereLight,
                    UsdLux.DiskLight,
                    UsdLux.DistantLight,
                )
            ):
                continue

            # Intensity
            intensity = rng.uniform(*intensity_range)
            light = UsdLux.LightAPI(prim)
            light.CreateIntensityAttr(intensity)

            # Colour temperature → RGB
            rgb = self._kelvin_to_rgb(rng.uniform(*cct_range))
            light.CreateColorAttr(Gf.Vec3f(*rgb))

            # Shadow softness (only RectLight and DistantLight support it natively)
            if prim.IsA(UsdLux.RectLight):
                UsdLux.ShapingAPI.Apply(prim)
                # shadow:blur maps to softness in Kit renderer
                shadow_attr = prim.GetAttribute("inputs:shadow:blur")
                if shadow_attr:
                    shadow_attr.Set(rng.uniform(*shadow_softness_range))

        # Global environment dome (optional — only if present)
        dome_path = f"{self._lighting_path}/EnvDome"
        dome_prim = self._stage.GetPrimAtPath(dome_path)
        if dome_prim.IsValid():
            dome_light = UsdLux.DomeLight(dome_prim)
            dome_light.CreateIntensityAttr(rng.uniform(50.0, 500.0))

    @staticmethod
    def _kelvin_to_rgb(temp_k: float) -> Tuple[float, float, float]:
        """Approximate Planckian locus → sRGB (Tanner Helland algorithm)."""
        temp_k = max(1000.0, min(temp_k, 40000.0))
        t = temp_k / 100.0

        if t <= 66.0:
            r = 1.0
            g = max(0.0, min(1.0, (99.4708025861 * math.log(t) - 161.1195681661) / 255.0))
        else:
            r = max(0.0, min(1.0, (329.698727446 * (t - 60.0) ** -0.1332047592) / 255.0))
            g = max(0.0, min(1.0, (288.1221695283 * (t - 60.0) ** -0.0755148492) / 255.0))

        if t >= 66.0:
            b = 1.0
        elif t <= 19.0:
            b = 0.0
        else:
            b = max(0.0, min(1.0, (138.5177312231 * math.log(t - 10.0) - 305.0447927307) / 255.0))

        return (r, g, b)

    # ------------------------------------------------------------------
    # Texture / material randomisation
    # ------------------------------------------------------------------

    def randomize_textures(self, seed: Optional[int] = None) -> None:
        """
        Swap MDL materials on floor, walls and racks from the asset library.
        Uses omni.replicator.core material randomisation where possible,
        falls back to direct USD material rebinding.
        """
        rng = random.Random(seed)

        # ---- Floor ----
        floor_prim = self._stage.GetPrimAtPath(f"{self._warehouse_path}/Floor")
        if floor_prim.IsValid():
            mdl = rng.choice(_FLOOR_MDL_VARIANTS)
            self._rebind_mdl(floor_prim, "FloorMat_Rand", mdl)

        # ---- Walls ----
        for wall_name in ("Wall_North", "Wall_South", "Wall_East", "Wall_West"):
            wall_prim = self._stage.GetPrimAtPath(
                f"{self._warehouse_path}/{wall_name}"
            )
            if wall_prim.IsValid():
                mdl = rng.choice(_WALL_MDL_VARIANTS)
                self._rebind_mdl(wall_prim, f"{wall_name}Mat_Rand", mdl)

        # ---- Racks ----
        racks_prim = self._stage.GetPrimAtPath(self._racks_path)
        if racks_prim.IsValid():
            mdl = rng.choice(_RACK_MDL_VARIANTS)
            for rack_prim in racks_prim.GetChildren():
                self._rebind_mdl(rack_prim, "RackMat_Rand", mdl)

        # ---- Replicator material randomisation (runtime) ----
        with rep.new_layer():
            if floor_prim.IsValid():
                rep.randomizer.materials(
                    [f"{self._warehouse_path}/Floor"],
                    on=rep.trigger.on_frame(),
                )

    def _rebind_mdl(
        self, prim: Usd.Prim, mat_name: str, mdl_path: str
    ) -> None:
        """Create (or reuse) an MDL material prim and bind it to `prim`."""
        scope = "/World/Looks"
        mat_stage_path = f"{scope}/{mat_name}"

        mat_prim = self._stage.GetPrimAtPath(mat_stage_path)
        if not mat_prim.IsValid():
            material = UsdShade.Material.Define(self._stage, mat_stage_path)
            shader = UsdShade.Shader.Define(
                self._stage, f"{mat_stage_path}/Shader"
            )
            shader.CreateIdAttr("mdlMaterial")
            shader.CreateInput("module", Sdf.ValueTypeNames.Asset).Set(mdl_path)
            material.CreateSurfaceOutput("mdl").ConnectToSource(
                shader.ConnectableAPI(), "out"
            )
            mat_prim = self._stage.GetPrimAtPath(mat_stage_path)

        binding_api = UsdShade.MaterialBindingAPI(prim)
        material = UsdShade.Material(mat_prim)
        binding_api.Bind(material)

    # ------------------------------------------------------------------
    # Worker / character randomisation
    # ------------------------------------------------------------------

    def randomize_worker_count(
        self,
        seed: Optional[int] = None,
        min_workers: int = 0,
        max_workers: int = 20,
        floor_bounds: Tuple[float, float, float, float] = (5.0, 5.0, 115.0, 55.0),
    ) -> List[str]:
        """
        Remove existing worker prims then spawn between min_workers and
        max_workers animated human characters at random floor positions.

        Returns a list of USD paths for the spawned workers.
        """
        rng = random.Random(seed)
        self._clear_prims_in_scope(f"{self._actors_path}/Workers")

        count = rng.randint(min_workers, max_workers)
        x_min, y_min, x_max, y_max = floor_bounds
        spawned_paths: List[str] = []

        for i in range(count):
            asset = rng.choice(_WORKER_USD_PATHS)
            x = rng.uniform(x_min, x_max)
            y = rng.uniform(y_min, y_max)
            heading = rng.uniform(0.0, 360.0)
            path = f"{self._actors_path}/Workers/Worker_{i:04d}"

            from isaacsim.core.utils.stage import add_reference_to_stage
            ref_prim = add_reference_to_stage(usd_path=asset, prim_path=path)
            prim = self._stage.GetPrimAtPath(path)
            if prim.IsValid():
                xf = UsdGeom.Xformable(prim)
                xf.AddTranslateOp().Set(Gf.Vec3d(x, y, 0.0))
                xf.AddRotateZOp().Set(heading)
                self._worker_prims.append(prim)
                spawned_paths.append(path)

        return spawned_paths

