    # ------------------------------------------------------------------
    # Inventory randomisation
    # ------------------------------------------------------------------

    def randomize_inventory(
        self,
        seed: Optional[int] = None,
        fill_ratio: float = 0.7,
        box_size_range: Tuple[Tuple[float, float], ...] = (
            (0.2, 0.6),  # half-extents X
            (0.2, 0.6),  # half-extents Y
            (0.15, 0.5), # half-extents Z
        ),
    ) -> int:
        """
        Fill rack beam levels with box prims. Each box gets a randomised
        colour from _BOX_COLOURS and a randomised size within box_size_range.

        Returns the total number of boxes placed.
        """
        rng = random.Random(seed)
        racks_prim = self._stage.GetPrimAtPath(self._racks_path)
        if not racks_prim.IsValid():
            return 0

        self._clear_prims_in_scope(f"{self._actors_path}/Inventory")
        inv_scope = f"{self._actors_path}/Inventory"
        self._ensure_scope(inv_scope)

        box_count = 0
        for rack_prim in racks_prim.GetChildren():
            rack_path = str(rack_prim.GetPath())
            # Collect beam level Z positions (rough heuristic from Upright height)
            beam_levels = self._estimate_beam_levels(rack_prim)
            rack_xform = self._get_world_translate(rack_prim)

            for level_z in beam_levels:
                if rng.random() > fill_ratio:
                    continue
                # Place 1-3 boxes per level per bay
                for b in range(rng.randint(1, 3)):
                    if rng.random() > fill_ratio:
                        continue
                    bx = rng.uniform(*box_size_range[0])
                    by = rng.uniform(*box_size_range[1])
                    bz = rng.uniform(*box_size_range[2])
                    colour = rng.choice(_BOX_COLOURS)

                    box_path = f"{inv_scope}/Box_{box_count:06d}"
                    cube = UsdGeom.Cube.Define(self._stage, box_path)
                    prim = self._stage.GetPrimAtPath(box_path)
                    xf = UsdGeom.Xformable(prim)
                    xf.AddTranslateOp().Set(
                        Gf.Vec3d(
                            rack_xform[0] + rng.uniform(-0.5, 0.5),
                            rack_xform[1] + rng.uniform(-0.3, 0.3),
                            level_z + bz,
                        )
                    )
                    xf.AddScaleOp().Set(Gf.Vec3f(bx, by, bz))

                    # Colour via display colour
                    UsdGeom.Gprim(prim).CreateDisplayColorAttr(
                        [Gf.Vec3f(*colour)]
                    )
                    box_count += 1

        return box_count

    def _estimate_beam_levels(self, rack_prim: Usd.Prim) -> List[float]:
        """Return approximate Z heights of beam levels for a rack prim."""
        # If real asset: inspect children named Beam_*
        levels: List[float] = []
        for child in rack_prim.GetChildren():
            name = child.GetName()
            if "Beam" in name or "Level" in name:
                t = child.GetAttribute("xformOp:translate")
                if t:
                    val = t.Get()
                    if val:
                        levels.append(float(val[2]))
        if not levels:
            # Fallback: evenly spaced levels
            levels = [1.0 + i * 1.2 for i in range(4)]
        return sorted(levels)

    def _get_world_translate(self, prim: Usd.Prim) -> Tuple[float, float, float]:
        t_attr = prim.GetAttribute("xformOp:translate")
        if t_attr:
            val = t_attr.Get()
            if val:
                return (float(val[0]), float(val[1]), float(val[2]))
        return (0.0, 0.0, 0.0)

    # ------------------------------------------------------------------
    # Time of day
    # ------------------------------------------------------------------

    def randomize_time_of_day(
        self,
        seed: Optional[int] = None,
        hour_range: Tuple[float, float] = (5.0, 21.0),
    ) -> float:
        """
        Adjust sun elevation and intensity to simulate a random hour.

        Returns the chosen hour (float, 0-24).
        """
        rng = random.Random(seed)
        hour = rng.uniform(*hour_range)

        # Sun elevation angle: peaks at noon, zero at horizon
        elevation = max(0.0, 90.0 * math.sin(math.pi * (hour - 6.0) / 12.0))
        azimuth = 180.0 + (hour - 12.0) * 15.0  # 15°/hr

        sun_prim = self._stage.GetPrimAtPath(f"{self._lighting_path}/Sun")
        if sun_prim.IsValid():
            xf = UsdGeom.Xformable(sun_prim)
            # Clear existing rotation ops and set new values
            ops = xf.GetOrderedXformOps()
            for op in ops:
                if op.GetOpType() == UsdGeom.XformOp.TypeRotateXYZ:
                    op.Set(Gf.Vec3f(elevation, 0.0, azimuth))
                    break
            else:
                xf.AddRotateXYZOp().Set(Gf.Vec3f(elevation, 0.0, azimuth))

            sun_light = UsdLux.DistantLight(sun_prim)
            intensity = max(0.0, 1500.0 * math.sin(math.pi * (hour - 6.0) / 12.0))
            sun_light.CreateIntensityAttr(intensity)

        return hour

    # ------------------------------------------------------------------
    # Weather effects
    # ------------------------------------------------------------------

    def randomize_weather(
        self,
        seed: Optional[int] = None,
        weather_types: Tuple[str, ...] = ("clear", "dusty", "foggy", "wet"),
    ) -> str:
        """
        Simulate environmental conditions using Replicator particle / fog nodes.

        Returns the selected weather type.
        """
        rng = random.Random(seed)
        weather = rng.choice(weather_types)

        with rep.new_layer():
            if weather == "dusty":
                self._apply_dust_particles(rng)
            elif weather == "foggy":
                self._apply_fog(rng)
            elif weather == "wet":
                self._apply_wet_floor(rng)
            # "clear" — no additional FX

        return weather

    def _apply_dust_particles(self, rng: random.Random) -> None:
        """Spawn floating dust particle system via Replicator."""
        with rep.new_layer():
            particles = rep.create.particles(
                position=(60.0, 30.0, 4.5),
                spread=(55.0, 25.0, 2.0),
                count=rng.randint(500, 2000),
                size=rng.uniform(0.005, 0.02),
                color=(0.85, 0.75, 0.55, 0.3),   # RGBA
                velocity=(rng.uniform(-0.2, 0.2), rng.uniform(-0.1, 0.1), 0.0),
                lifetime=rng.uniform(5.0, 15.0),
            )

    def _apply_fog(self, rng: random.Random) -> None:
        """Set scene-level exponential height fog parameters."""
        # omni.kit.commands provides scene settings API
        try:
            import omni.kit.commands
            omni.kit.commands.execute(
                "SetFogSettings",
                density=rng.uniform(0.01, 0.08),
                height_falloff=rng.uniform(0.1, 0.5),
                fog_color=(0.8, 0.8, 0.82),
                enable=True,
            )
        except Exception:
            # Fallback: create a volumetric cube proxy
            fog_path = f"{self._warehouse_path}/Fog"
            if not self._stage.GetPrimAtPath(fog_path).IsValid():
                UsdGeom.Cube.Define(self._stage, fog_path)
            prim = self._stage.GetPrimAtPath(fog_path)
            UsdGeom.Xformable(prim).AddTranslateOp().Set(Gf.Vec3d(60, 30, 4.5))
            UsdGeom.Xformable(prim).AddScaleOp().Set(
                Gf.Vec3f(60, 30, rng.uniform(1.0, 5.0))
            )

    def _apply_wet_floor(self, rng: random.Random) -> None:
        """Make floor material appear wet by swapping to a wet MDL variant."""
        wet_mdl = (
            "omniverse://localhost/NVIDIA/Assets/Warehouse/Materials/"
            "ConcreteFloor_Wet.mdl"
        )
        floor_prim = self._stage.GetPrimAtPath(f"{self._warehouse_path}/Floor")
        if floor_prim.IsValid():
            self._rebind_mdl(floor_prim, "WetFloorMat", wet_mdl)

        # Add puddle decals
        puddle_count = rng.randint(3, 12)
        for i in range(puddle_count):
            puddle_path = f"{self._warehouse_path}/Puddle_{i:02d}"
            if not self._stage.GetPrimAtPath(puddle_path).IsValid():
                UsdGeom.Plane.Define(self._stage, puddle_path)
            prim = self._stage.GetPrimAtPath(puddle_path)
            xf = UsdGeom.Xformable(prim)
            xf.AddTranslateOp().Set(
                Gf.Vec3d(
                    rng.uniform(5.0, 115.0),
                    rng.uniform(5.0, 55.0),
                    0.002,
                )
            )
            xf.AddScaleOp().Set(
                Gf.Vec3f(rng.uniform(0.3, 1.5), rng.uniform(0.3, 1.5), 1.0)
            )

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _ensure_actors_scope(self) -> None:
        self._ensure_scope(self._actors_path)
        self._ensure_scope(f"{self._actors_path}/Workers")
        self._ensure_scope(f"{self._actors_path}/Forklifts")

    def _ensure_scope(self, path: str) -> None:
        prim = self._stage.GetPrimAtPath(path)
        if not prim.IsValid():
            UsdGeom.Scope.Define(self._stage, path)

    def _clear_prims_in_scope(self, scope_path: str) -> None:
        """Delete all children of a scope prim."""
        scope_prim = self._stage.GetPrimAtPath(scope_path)
        if not scope_prim.IsValid():
            self._ensure_scope(scope_path)
            return
        for child in list(scope_prim.GetChildren()):
            self._stage.RemovePrim(child.GetPath())
